def embedded_app_icon() -> QIcon:
    """QIcon with every size of the embedded StampPhoto icon."""
    icon = QIcon()
    for data in _PNG_BASE64.values():
        pixmap = QPixmap()
        if pixmap.loadFromData(QByteArray(base64.b64decode("".join(data))), "PNG"):
            icon.addPixmap(pixmap)
    return icon


def embedded_app_pixmap(size: int = 256) -> QPixmap:
    """The embedded icon at the given size (for the About dialog logo)."""
    return embedded_app_icon().pixmap(size, size)
